/**
 * Resolves the environment settings for one organisation's backend process.
 *
 * Required wallet and database details are validated before the server starts. This avoids a
 * backend appearing healthy when it could not sign transactions or reach the data it claims to hold.
 */
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Both src and dist sit one level below the backend package root.
const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

export const config = {
  fabricChannelName: process.env.FABRIC_CHANNEL_NAME ?? "milkchannel",
  // These names must match the committed chaincode definitions and cross-chaincode call.
  stakeholderChaincodeName: "stakeholder",
  supplychainChaincodeName: "supplychain",
  // Only organisations with an off-chain store require this value.
  databaseUrl: process.env.DATABASE_URL?.trim() || undefined,
  // Persists the regulator listener's position across restarts.
  eventCheckpointPath: process.env.EVENT_CHECKPOINT_PATH ?? ".fabric-events.checkpoint",
  // Root of the organisation wallets generated by the local network.
  fabricOrganizationsPath:
    process.env.FABRIC_ORGANIZATIONS_PATH ??
    join(repositoryRoot, "fabric", "milk-network", "organizations", "peerOrganizations")
};
